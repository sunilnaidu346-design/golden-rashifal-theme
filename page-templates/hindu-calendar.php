<h2>हिंदू कैलेंडर की बुनियादी संरचना</h2>
<p>Western (Gregorian) calendar सूर्य पर based है — 365 दिन, 12 महीने। Islamic calendar purely lunar है — 354 दिन। हिंदू कैलेंडर दोनों को combine करता है — इसलिए इसे "lunisolar" कहते हैं।</p>

<p>एक चंद्र मास (lunar month) = 29.5 दिन approximately। 12 चंद्र मास = 354 दिन। Solar year = 365.25 दिन। इस 11 दिन के gap को balance करने के लिए हर 2-3 साल में एक "अधिक मास" (extra month) जोड़ा जाता है।</p>

<h2>हिंदू कैलेंडर के 12 महीने</h2>

<p><strong>1. चैत्र</strong> (मार्च-अप्रैल) — हिंदू नव वर्ष की शुरुआत। नवरात्रि इसी में।</p>
<p><strong>2. वैशाख</strong> (अप्रैल-मई) — अक्षय तृतीया, बुद्ध पूर्णिमा।</p>
<p><strong>3. ज्येष्ठ</strong> (मई-जून) — गंगा दशहरा, निर्जला एकादशी।</p>
<p><strong>4. आषाढ़</strong> (जून-जुलाई) — गुरु पूर्णिमा, देवशयनी एकादशी।</p>
<p><strong>5. श्रावण</strong> (जुलाई-अगस्त) — सबसे पवित्र महीना। कावड़ यात्रा, रक्षाबंधन।</p>
<p><strong>6. भाद्रपद</strong> (अगस्त-सितंबर) — गणेश चतुर्थी, जन्माष्टमी।</p>
<p><strong>7. आश्विन</strong> (सितंबर-अक्टूबर) — शारदीय नवरात्रि, दशहरा, शरद पूर्णिमा।</p>
<p><strong>8. कार्तिक</strong> (अक्टूबर-नवंबर) — दीपावली, छठ पूजा, देवउठनी एकादशी।</p>
<p><strong>9. मार्गशीर्ष</strong> (नवंबर-दिसंबर) — गीता जयंती। भगवान कृष्ण ने गीता में कहा "मासानां मार्गशीर्षोऽहम्" (महीनों में मैं मार्गशीर्ष हूँ)।</p>
<p><strong>10. पौष</strong> (दिसंबर-जनवरी) — मकर संक्रांति, लोहड़ी।</p>
<p><strong>11. माघ</strong> (जनवरी-फरवरी) — माघ स्नान, बसंत पंचमी।</p>
<p><strong>12. फाल्गुन</strong> (फरवरी-मार्च) — महाशिवरात्रि, होली।</p>

<h2>पक्ष — शुक्ल और कृष्ण</h2>
<p>हर चंद्र मास दो पक्षों में बँटा है:</p>
<p><strong>शुक्ल पक्ष</strong> — अमावस्या के बाद शुरू, चाँद बढ़ता है, पूर्णिमा पर ख़त्म। "Waxing" phase।</p>
<p><strong>कृष्ण पक्ष</strong> — पूर्णिमा के बाद शुरू, चाँद घटता है, अमावस्या पर ख़त्म। "Waning" phase।</p>

<p>कुछ regions पूर्णिमान्त (month ends on Purnima) follow करते हैं, कुछ अमान्त (month ends on Amavasya)। उत्तर भारत में mostly पूर्णिमान्त, दक्षिण भारत में अमान्त।</p>

<h2>तिथि — हिंदू कैलेंडर की basic unit</h2>
<p>जैसे Gregorian calendar में "date" होती है, वैसे ही हिंदू कैलेंडर में "तिथि" होती है। लेकिन एक बड़ा difference — तिथि fixed 24 hours की नहीं होती।</p>

<p>तिथि चंद्रमा और सूर्य के बीच angular distance पर depend करती है (हर 12° = 1 तिथि)। इसलिए कोई तिथि 20 घंटे की हो सकती है, कोई 26 घंटे की। यही कारण है कि कभी-कभी एक ही date पर दो तिथियाँ आ जाती हैं, या एक तिथि दो dates पर spread हो जाती है।</p>

<h3>15 तिथियाँ</h3>
<p>प्रतिपदा, द्वितीया, तृतीया, चतुर्थी, पंचमी, षष्ठी, सप्तमी, अष्टमी, नवमी, दशमी, एकादशी, द्वादशी, त्रयोदशी, चतुर्दशी, पूर्णिमा/अमावस्या।</p>

<h2>संवत (Era) Systems</h2>

<h3>विक्रम संवत</h3>
<p>सबसे widely used भारतीय calendar era। 57 BCE में शुरू हुआ (राजा विक्रमादित्य के नाम पर)। 2026 AD = विक्रम संवत 2081-2082। Nepal का official calendar भी Vikram Samvat based है।</p>

<h3>शक संवत</h3>
<p>भारत सरकार का official calendar। 78 AD में शुरू। 2026 AD = शक संवत 1947। Indian government documents, All India Radio, और Doordarshan इसे use करते हैं।</p>

<h2>नक्षत्र — 27 तारा-समूह</h2>
<p>पंचांग में तिथि के साथ "नक्षत्र" भी दिया जाता है। आकाश को 27 equal parts में बाँटा गया है — हर part एक नक्षत्र। चंद्रमा हर दिन एक नक्षत्र से गुज़रता है (approximately)।</p>

<p>27 नक्षत्र: अश्विनी, भरणी, कृत्तिका, रोहिणी, मृगशिरा, आर्द्रा, पुनर्वसु, पुष्य, आश्लेषा, मघा, पूर्वाफाल्गुनी, उत्तराफाल्गुनी, हस्त, चित्रा, स्वाती, विशाखा, अनुराधा, ज्येष्ठा, मूल, पूर्वाषाढ़ा, उत्तराषाढ़ा, श्रवण, धनिष्ठा, शतभिषा, पूर्वाभाद्रपद, उत्तराभाद्रपद, रेवती।</p>

<h2>हिंदू कैलेंडर vs Gregorian Calendar</h2>

<ul style="list-style:disc;padding-left:1.4em;margin-bottom:1.2em">
<li>Hindu = lunisolar, Gregorian = solar</li>
<li>Hindu month शुक्ल प्रतिपदा से शुरू, Gregorian month 1st date से</li>
<li>Hindu calendar में अधिक मास (leap month), Gregorian में leap day (29 Feb)</li>
<li>Hindu calendar regional variations हैं, Gregorian worldwide uniform</li>
<li>Hindu festivals lunar date पर, national holidays solar date पर</li>
</ul>

