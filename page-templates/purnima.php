<h2>विशेष पूर्णिमाएँ</h2>

<h3>शरद पूर्णिमा (आश्विन)</h3>
<p>साल की सबसे खास पूर्णिमा मानी जाती है। इस रात चाँद की किरणों में अमृत बरसता है — ऐसी पारंपरिक मान्यता है। खीर रखकर चाँदनी में रखने की परंपरा है। माना जाता है कि इस रात चंद्रमा सबसे चमकदार और सबसे करीब होता है।</p>

<h3>गुरु पूर्णिमा (आषाढ़)</h3>
<p>गुरुओं का सम्मान करने का दिन। वेद व्यास जी का जन्मदिन भी इसी दिन माना जाता है। शिक्षकों, mentors, और spiritual guides को धन्यवाद देने का अवसर।</p>

<h3>कार्तिक पूर्णिमा</h3>
<p>"देव दीपावली" — इस दिन देवता दीपक जलाकर उत्सव मनाते हैं — ऐसी मान्यता है। वाराणसी में गंगा घाटों पर लाखों दीपक जलाए जाते हैं। बहुत सुंदर दृश्य होता है।</p>

